import assert from 'node:assert/strict';
import {test} from 'node:test';
import {chromium} from 'playwright-core';

const origin = process.env.OMNIRELAY_BROWSER_ORIGIN;
test('项目管理员通过成员选择器授予和撤销，提交后的重试只读目标', {skip:!origin}, async t => {
  const browser = await chromium.launch({executablePath:process.env.OMNIRELAY_CHROME});
  t.after(() => browser.close());
  const page = await browser.newPage({ignoreHTTPSErrors:true,viewport:{width:1366,height:900}});
  page.setDefaultTimeout(6000);
  await page.goto(origin + '/#/system/users');
  await page.locator('#login-username').fill('project_operator');
  await page.locator('#login-password').fill('fixture-password-only');
  await page.locator('#password-login button[type=submit]').click();
  const target = page.locator('tr[data-row]').filter({hasText:'historical'});
  const view = target.locator('[data-admin-action=user]');
  await view.click();
  const drawer = page.locator('dialog.user-detail-drawer[open]');
  assert.equal(Math.round((await drawer.boundingBox()).width),480);
  await drawer.locator('[data-admin-action=add-role]').click();
  const role = drawer.locator('select[name=role]');
  await role.selectOption('project_admin');
  const projects = drawer.locator('select[name=scope]');
  await projects.focus();
  await projects.press('ArrowDown');
  assert.equal(await projects.inputValue(),'acceptance-project');
  await page.keyboard.press('Escape');
  await page.getByRole('button',{name:'继续编辑'}).click();
  assert.equal(await projects.inputValue(),'acceptance-project');
  const session = await (await page.request.get(origin+'/api/v1/me')).json();
  const account = await target.getAttribute('data-row');
  const membership = origin+'/api/v1/projects/acceptance-project/members/'+account+'/access';
  for (const memberRole of ['revoked','member']) {
    const response = await page.request.put(membership,{headers:{Origin:origin,'X-CSRF-Token':session.csrf_token},data:{role:memberRole}});
    assert.equal(response.status(),200);
  }
  const rejected = page.waitForResponse(res=>res.url().endsWith('/role-grants') && res.request().method()==='POST');
  await drawer.locator('[data-save-role]').click();
  assert.equal((await rejected).status(),409);
  await drawer.getByText('项目会籍已变更，请重新打开用户详情后选择项目。').waitFor();
  await drawer.locator('[data-admin-action=cancel-role]').click();
  await page.keyboard.press('Escape');
  await view.click();
  await drawer.locator('[data-admin-action=add-role]').click();
  await role.selectOption('project_admin');
  await projects.selectOption('acceptance-project');
  const reads = [];
  const userPages = [];
  page.on('request',r => {
    const url = new URL(r.url());
    if (url.pathname === '/api/v1/system/user-page') userPages.push(url.searchParams);
    if (url.pathname.startsWith('/api/v1/system/')) reads.push([r.method(),url.pathname]);
  });
  const path = '/api/v1/system/accounts/' + await target.getAttribute('data-row') + '/projects';
  await page.route(url=>url.pathname===path,route=>route.fulfill({status:503,body:'{}'}),{times:1});
  await drawer.locator('[data-save-role]').click();
  await drawer.getByRole('button',{name:'变更已提交，重新读取授权'}).click();
  await drawer.getByRole('button',{name:'撤销'}).waitFor();
  assert.match(await target.textContent(),/项目管理员/);
  assert.deepEqual(reads,[['POST','/api/v1/system/role-grants'],['GET',path],['GET',path]]);
  await page.keyboard.press('Escape');
  const counts = await (await page.request.get(origin+'/api/v1/system/role-counts')).json();
  assert.equal(counts.project_admin,1);
  await view.evaluate(el=>{if(el!==document.activeElement) throw Error('焦点未恢复');});
  await page.setViewportSize({width:390,height:844});
  await page.emulateMedia({colorScheme:'dark'});
  await page.getByRole('searchbox').fill('项目管理员');
  await page.getByText('共 1 条',{exact:true}).waitFor();
  await view.click();
  assert.equal(Math.round((await drawer.boundingBox()).width),390);
  await drawer.locator('[data-scope=project]').filter({hasText:'acceptance-project'}).waitFor();
  await drawer.locator('[data-admin-action=add-role]').click();
  await role.selectOption('project_admin');
  await projects.selectOption('acceptance-project');
  await drawer.locator('[data-save-role]').click();
  await drawer.getByText('该用户已有相同范围的角色授权。').waitFor();
  await drawer.locator('[data-admin-action=cancel-role]').click();
  reads.length=0;
  await drawer.getByRole('button',{name:'撤销'}).click();
  await page.getByRole('button',{name:'确认撤销'}).click();
  await drawer.getByRole('button',{name:'撤销'}).waitFor({state:'detached'});
  assert.equal(reads.length,3);
  assert.equal(reads[0][0],'DELETE');
  assert.deepEqual(reads[1],['GET',path]);
  assert.deepEqual(reads[2],['GET','/api/v1/system/user-page']);
  assert.equal(userPages.at(-1).get('limit'),'1');
  await page.getByText('共 0 条',{exact:true}).waitFor();
  await page.keyboard.press('Escape');
  await page.getByRole('searchbox').fill('');
  const noProjects = page.locator('tr[data-row]').filter({hasText:'auditor'}).locator('[data-admin-action=user]');
  await noProjects.click();
  await drawer.locator('[data-admin-action=add-role]').click();
  await role.selectOption('project_admin');
  await drawer.getByText('该用户没有可授权的项目。').waitFor();
  assert.equal(await drawer.locator('[data-save-role]').isDisabled(),true);
  await drawer.locator('[data-admin-action=cancel-role]').click();
  await page.keyboard.press('Escape');
  await page.route(url=>url.pathname===path,route=>route.fulfill({status:503,body:'{}'}),{times:1});
  await view.click();
  await drawer.getByRole('button',{name:'重新读取'}).click();
  await drawer.locator('[data-admin-action=add-role]').waitFor();
  await page.keyboard.press('Escape');
  async function loginAs(username) {
    const response = await page.request.post(origin+'/auth/login',{headers:{Origin:origin},
      data:{username,password:'fixture-password-only'}});
    assert.equal(response.status(),204);
    await page.goto(origin+'/#/system/users');
    await page.reload();
  }
  await loginAs('operator');
  await view.click();
  await drawer.getByText('当前账号无授权操作权限。').waitFor();
  assert.equal(await drawer.locator('[data-admin-action=add-role]').count(),0);
  await page.keyboard.press('Escape');
  await loginAs('admin');
  const self = page.locator('tr[data-row]').filter({has:page.getByText('admin',{exact:true})});
  await self.waitFor();
  assert.equal(await self.locator('[data-admin-action=toggle]').count(),0);
  const provision = page.locator('tr[data-row]').filter({hasText:'待开通成员'});
  await provision.locator('[data-admin-action=user]').click();
  await drawer.getByRole('button',{name:'开通账号'}).click();
  await page.getByRole('button',{name:'确认开通'}).click();
  await drawer.locator('[data-admin-action=add-role]').click();
  await role.selectOption('audit_viewer');
  reads.length = 0;
  await drawer.locator('[data-save-role]').click();
  await drawer.locator('.admin-grants').getByText('审计查看者').waitFor();
  assert.deepEqual(reads.map(([method,path])=>[method,path.split('/').at(-1)]),[
    ['POST','role-grants'],['GET',await provision.getAttribute('data-row')],['GET','role-grants']
  ]);
  await page.keyboard.press('Escape');
  for (const action of ['停用','启用']) {
    await provision.getByRole('button',{name:action}).click();
    await page.getByRole('button',{name:'确认'+action}).click();
    await provision.getByText('已'+action,{exact:true}).waitFor();
  }
  await page.goto(origin+'/#/system/roles');
  await page.locator('tr[data-row=audit_viewer]').waitFor();
  assert.equal(await page.locator('tr[data-row=audit_viewer] td').nth(3).textContent(),'2');
});
